RE_TITLE = re.compile(r"<title>.*?</title>\s*", re.I | re.S)
RE_META = re.compile(
    r'<meta\b[^>]*?\b(?:name|property)\s*=\s*["\'](?:description|og:title|og:description|og:url|twitter:title)["\'][^>]*>\s*', re.I)
RE_CANON = re.compile(r'<link\b[^>]*?rel\s*=\s*["\']canonical["\'][^>]*>\s*', re.I)
RE_CHARSET = re.compile(r"<meta\b[^>]*charset[^>]*>", re.I)
RE_BLOCK = re.compile(re.escape(START) + r".*?" + re.escape(END) + r"\s*", re.S)
RE_ASSET = re.compile(r'(\s(?:href|src)=")(css|js|engine)/')


def e(s):
    return html.escape(s, quote=True)


def nav_html():
    items = ['<a href="/%s/">%s</a>' % (r["path"], e(r["nav"])) for r in ROUTES if r["nav"]]
    return " &middot; ".join(items)


def seo_block(heading, paras):
    if not heading:
        return ""
    body = "".join("<p>%s</p>" % e(t) for t in paras)
    return (
        START + "\n"
        '<style>#seo-about{max-width:720px;margin:36px auto 48px;padding:0 20px;font:15px/1.6 system-ui,-apple-system,"Segoe UI",Roboto,sans-serif;opacity:.85}'
        "#seo-about h2{font-size:20px;margin:0 0 8px}#seo-about p{margin:8px 0}#seo-about a{color:inherit}"
        "body:has(#userbox:not(:empty)) #seo-about{display:none}</style>\n"   # hidden once someone is logged in
        '<section id="seo-about"><h2>%s</h2>%s'
        '<p><a href="/">Pawniac</a> &middot; %s</p></section>\n' % (e(heading), body, nav_html())
        + END + "\n"
    )


def head_tags(r):
    url = "%s/%s/" % (DOMAIN, r["path"])
    t, d = e(r["title"]), e(r["desc"])
    return ('\n<title>%s</title>\n<meta name="description" content="%s">\n<link rel="canonical" href="%s">\n'
            '<meta property="og:title" content="%s">\n<meta property="og:description" content="%s">\n'
            '<meta property="og:url" content="%s">\n<meta name="twitter:title" content="%s">\n'
            % (t, d, url, t, d, url, t))


def insert_block(s, block):
    """Put the block right after the page's own content (before the first <script> in <body>)."""
    if not block:
        return s
    b = re.search(r"<body[^>]*>", s, re.I)
    start = b.end() if b else 0
    m = re.search(r"<script\b", s[start:], re.I)
    i = start + m.start() if m else len(s)
    return s[:i] + block + s[i:]


def make_shell(base, r):
    s = RE_TITLE.sub("", base, count=1)
    s = RE_META.sub("", s)
    s = RE_CANON.sub("", s)
    m = RE_CHARSET.search(s) or re.search(r"<head[^>]*>", s, re.I)
    s = s[: m.end()] + head_tags(r) + s[m.end():]
    s = RE_ASSET.sub(r"\1/\2/", s)                       # css/x.css -> /css/x.css so it works in a subfolder
    s = re.sub(r"(<!DOCTYPE[^>]*>)", r"\1\n<!-- " + MARK + ": do not edit -->", s, count=1, flags=re.I)
    return insert_block(s, seo_block(r["h"], r["text"]))


def main():
    index = ROOT / "index.html"
    if not index.exists():
        sys.exit("index.html not found next to tools/")
    raw = index.read_text(encoding="utf-8")
    base = RE_BLOCK.sub("", raw)                         # the home page without our block

    # home page: refresh the text block + links for Google (nothing else is touched)
    new_home = insert_block(base, seo_block(HOME_H, HOME_TEXT))
    if new_home != raw:
        index.write_text(new_home, encoding="utf-8")

    made, skipped = [], []
    for r in ROUTES:
        target = ROOT / r["path"] / "index.html"
        if target.exists() and MARK not in target.read_text(encoding="utf-8", errors="ignore"):
            skipped.append(r["path"])
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(make_shell(base, r), encoding="utf-8")
        made.append(r["path"])

    today = date.today().isoformat()
    urls = [DOMAIN + "/"] + ["%s/%s/" % (DOMAIN, r["path"]) for r in ROUTES if r["sitemap"]]
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    lines += ["  <url><loc>%s</loc><lastmod>%s</lastmod></url>" % (u, today) for u in urls]
    lines.append("</urlset>\n")
    (ROOT / "sitemap.xml").write_text("\n".join(lines), encoding="utf-8")

    rb = ROOT / "robots.txt"
    if not rb.exists():
        rb.write_text("User-agent: *\nAllow: /\n\nSitemap: %s/sitemap.xml\n" % DOMAIN, encoding="utf-8")

    print("pages made   :", ", ".join(made))
    print("pages skipped:", ", ".join(skipped) or "none")
    print("sitemap.xml  : %d URLs" % len(urls))


if __name__ == "__main__":
    main()
