  function esc(s){ return String(s).replace(/[&<>"']/g, function(c){ return {'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]; }); }
  function winPct(cp){ cp = Math.max(-1000, Math.min(1000, cp)); return 50 + 50 * (2 / (1 + Math.exp(-0.00368208 * cp)) - 1); }
  function pov(A, cp){ return A.me === 'w' ? cp : -cp; }

  // ---------- vector chess board (no images, so it always prints) ----------
  function boardSvg(fen, last, arrow, flip, px){
    var grid = [];
    fen.split(' ')[0].split('/').forEach(function(row){
      var line = [];
      for(var i = 0; i < row.length; i++){
        var ch = row.charAt(i);
        if(/\d/.test(ch)){ for(var k = 0; k < +ch; k++) line.push(null); } else line.push(ch);
      }
      grid.push(line);
    });
    function pos(sq){ var f = sq.charCodeAt(0) - 97, r = 8 - parseInt(sq.charAt(1), 10); return {x:flip ? 7 - f : f, y:flip ? 7 - r : r}; }
    var s = '<svg class="bd" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 8 8" width="' + px + '" height="' + px + '">';
    for(var dy = 0; dy < 8; dy++) for(var dx = 0; dx < 8; dx++)
      s += '<rect x="' + dx + '" y="' + dy + '" width="1" height="1" fill="' + (((dx + dy) % 2 === 0) ? '#f0d9b5' : '#b58863') + '"/>';
    if(last) [last.from, last.to].forEach(function(sq){ var p = pos(sq); s += '<rect x="' + p.x + '" y="' + p.y + '" width="1" height="1" fill="#f6f669" fill-opacity=".55"/>'; });
    for(var i = 0; i < 8; i++){
      var fileCh = flip ? 'hgfedcba'.charAt(i) : 'abcdefgh'.charAt(i), rankCh = flip ? (i + 1) : (8 - i);
      s += '<text x="' + (i + .94) + '" y="7.93" font-size=".22" text-anchor="end" font-weight="700" font-family="Arial,sans-serif" fill="' + (((i + 7) % 2 === 0) ? '#b58863' : '#f0d9b5') + '">' + fileCh + '</text>';
      s += '<text x=".06" y="' + (i + .25) + '" font-size=".22" font-weight="700" font-family="Arial,sans-serif" fill="' + ((i % 2 === 0) ? '#b58863' : '#f0d9b5') + '">' + rankCh + '</text>';
    }
    for(var r = 0; r < 8; r++) for(var f = 0; f < 8; f++){
      var ch2 = grid[r] && grid[r][f];
      if(!ch2) continue;
      var white = ch2 === ch2.toUpperCase(), t = ch2.toLowerCase(), px2 = flip ? 7 - f : f, py2 = flip ? 7 - r : r;
      s += '<text x="' + (px2 + .5) + '" y="' + (py2 + .5) + '" dy=".31" font-size=".92" text-anchor="middle" font-family="' + SYM_FONTS + '" fill="' + (white ? '#ffffff' : '#1a1a1a') +
           '" stroke="' + (white ? '#1a1a1a' : '#ffffff') + '" stroke-width=".05" paint-order="stroke">' + GLYPH[t] + '\uFE0E</text>';
    }
    if(arrow){
      var a = pos(arrow.from), b = pos(arrow.to), x1 = a.x + .5, y1 = a.y + .5, x2 = b.x + .5, y2 = b.y + .5;
      var ddx = x2 - x1, ddy = y2 - y1, len = Math.sqrt(ddx * ddx + ddy * ddy) || 1, ux = ddx / len, uy = ddy / len;
      var bx = x2 - ux * .4, by = y2 - uy * .4, nx = -uy, ny = ux;
      s += '<line x1="' + x1 + '" y1="' + y1 + '" x2="' + bx + '" y2="' + by + '" stroke="#1f9d55" stroke-width=".16" stroke-linecap="round" opacity=".88"/>';
      s += '<polygon points="' + (x2 - ux * .08) + ',' + (y2 - uy * .08) + ' ' + (bx + nx * .23) + ',' + (by + ny * .23) + ' ' + (bx - nx * .23) + ',' + (by - ny * .23) + '" fill="#1f9d55" opacity=".92"/>';
    }
    return s + '</svg>';
  }

  // ---------- evaluation graph (cream = your winning chances) with your slips marked ----------
  function graphSvg(A){
    var n = A.fens.length, W = 640, H = 84, pts = [], dots = '';
    for(var i = 0; i < n; i++){
      var x = n > 1 ? i / (n - 1) * W : 0;
      pts.push(x.toFixed(1) + ',' + (H - winPct(pov(A, A.ev[i].cp)) / 100 * H).toFixed(1));
    }
    A.moves.forEach(function(m, i){
      if(m.color !== A.me) return;
      var lb = A.stats[i].label;
      if(lb !== 'inaccuracy' && lb !== 'mistake' && lb !== 'blunder') return;
      var x = n > 1 ? (i + 1) / (n - 1) * W : 0, y = H - winPct(pov(A, A.ev[i + 1].cp)) / 100 * H;
      dots += '<circle cx="' + x.toFixed(1) + '" cy="' + y.toFixed(1) + '" r="4.5" fill="' + LAB[lb][1] + '" stroke="#fff" stroke-width="1.2"/>';
    });
    return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ' + W + ' ' + H + '" width="100%" height="' + H + '" preserveAspectRatio="none">' +
      '<rect width="' + W + '" height="' + H + '" fill="#2b2924"/><polygon points="0,' + H + ' ' + pts.join(' ') + ' ' + W + ',' + H + '" fill="#f4f1ea"/>' +
      '<line x1="0" y1="' + H / 2 + '" x2="' + W + '" y2="' + H / 2 + '" stroke="#999" stroke-width="1" stroke-dasharray="4 4" opacity=".7"/>' + dots + '</svg>';
  }

  // the Pawniac logo, taken from the page header
  function logoSvg(cls){
    var el = document.querySelector('.brand-logo');
    if(!el) return '<span class="' + cls + '">P</span>';
    return el.outerHTML.replace(/class="[^"]*"/, 'class="' + cls + '"');
  }

  // ---------- pages: fill each A4 page with whole blocks (a block is never cut in half) ----------
  function paginate(heights, keeps, limit){
    var pages = [[]], cur = 0;
    for(var i = 0; i < heights.length; i++){
      var h = heights[i], need = h + ((keeps[i] && i + 1 < heights.length) ? heights[i + 1] : 0);
      if(cur > 0 && cur + need > limit){ pages.push([]); cur = 0; }
      pages[pages.length - 1].push(i);
      cur += h;
    }
    return pages;
  }

  // ---------- what goes in the report ----------
  function reportCards(H){
    var tmp = document.createElement('div'), out = [];
    tmp.innerHTML = H.report();
    tmp.querySelectorAll('.an-moment').forEach(function(s){ s.replaceWith(document.createTextNode(s.textContent)); });
    var pb = tmp.querySelector('#anToPractice'); if(pb) pb.remove();
    Array.prototype.forEach.call(tmp.children, function(c){
      if(!c.classList.contains('card')) return;
      var h = c.querySelector('h2');
      if(h && /Learn from your mistakes/i.test(h.textContent)) return;          // practice is interactive: not in the PDF
      out.push(c.outerHTML.replace(' Click one to jump to it.', '').replace(' (Games played on Pawniac do not record per-move times yet.)', ''));
    });
    return out;
  }

  function moveHtml(H, A, k){
    var m = A.moves[k - 1], S = A.stats[k - 1], mine = (m.color === A.me), flip = (A.me === 'b'), panel = H.panel(k);
    try{ if(window.__c45Html) panel += window.__c45Html(A, k, panel.replace(/<[^>]+>/g, ' ')); }catch(e){}
    if(!mine) return '<div class="mv opp"><div class="txt">' + panel + '</div></div>';
    var bds = '<figure class="fig">' + boardSvg(A.fens[k], {from:m.from, to:m.to}, null, flip, 170) + '<figcaption>After your move</figcaption></figure>';
    var bad = (S.label === 'inaccuracy' || S.label === 'mistake' || S.label === 'blunder'), best = A.ev[k - 1].best;
    if(bad && best){
      bds += '<figure class="fig">' + boardSvg(A.fens[k - 1], null, {from:best.slice(0, 2), to:best.slice(2, 4)}, flip, 170) +
             '<figcaption>Before your move: the better move</figcaption></figure>';
    }
    return '<div class="mv mine"><div class="bds">' + bds + '</div><div class="txt">' + panel + '</div></div>';
  }

  function buildBlocks(H, A, cards){
    var B = [];
    var white = A.hdr.White || 'White', black = A.hdr.Black || 'Black', res = A.hdr.Result || '';
    var date = new Date().toLocaleDateString(undefined, {year:'numeric', month:'long', day:'numeric'});
    B.push({html:'<div class="cover">' + logoSvg('clogo') + '<div><div class="ctitle">Game Analysis Report</div><div class="csub">' + esc(white) + ' vs ' + esc(black) +
      (res ? ' &middot; ' + esc(res) : '') + '</div><div class="cmeta">Analysed from ' + (A.me === 'w' ? 'White' : 'Black') + "'s side &middot; " + date + '</div></div></div>'});
    cards.forEach(function(c){ B.push({html:c}); });
    var legend = Object.keys(LAB).map(function(k){ return '<span class="an-chip" style="background:' + LAB[k][1] + '">' + LAB[k][0] + '</span>'; }).join(' ');
    B.push({html:'<div class="card"><h2>How the game swung</h2>' + graphSvg(A) +
      '<p class="hint">The cream area is your winning chances: the higher the line, the better for you. Dots mark your inaccuracies, mistakes and blunders.</p>' +
      '<p class="legend">Move labels: ' + legend + '</p></div>'});
    B.push({html:'<h2 class="mh">Move-by-move coaching</h2><p class="desc">Every move of the game, with a coach explanation. Your moves have a board and a verdict; your opponent\'s moves are shorter. ' +
      'Evaluations always use the standard sign: + means White is ahead, - means Black is ahead.</p>', keep:true});
    for(var k = 1; k <= A.moves.length; k++) B.push({html:moveHtml(H, A, k)});
    return B;
  }

