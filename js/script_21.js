  function docHtml(blocks, title, white, black){
    var wm = '<div class="wm">' + logoSvg('wmlogo') + '</div>';
    var foot = '<div class="pftr">' + logoSvg('flogo') + '<span>' + CREDIT + '</span></div>';
    return '<!DOCTYPE html><html><head><meta charset="utf-8"><title>' + esc(title) + '</title><style>' + CSS + '</style></head><body>' +
      '<div id="probe" style="position:absolute;visibility:hidden;height:100mm;width:1px"></div>' +
      '<div id="src">' + blocks.map(function(b){ return '<div class="blk"' + (b.keep ? ' data-keep="1"' : '') + '>' + b.html + '</div>'; }).join('') + '</div>' +
      '<div id="pages"></div>' +
      '<script type="text/plain" id="tpl-wm">' + wm.replace(/<\//g, '<\\/') + '<\/script>' +
      '<script type="text/plain" id="tpl-ftr">' + foot.replace(/<\//g, '<\\/') + '<\/script>' +
      '</body></html>';
  }

  // measure the blocks inside the (hidden) print document, then build the real pages
  function layoutPages(d, title){
    var src = d.getElementById('src'), pagesEl = d.getElementById('pages');
    var blocks = Array.prototype.slice.call(src.children);
    var mm = d.getElementById('probe').getBoundingClientRect().height / 100 || 3.78;
    var limit = (297 - 22 - 20) * mm;
    var heights = blocks.map(function(b){ return b.getBoundingClientRect().height + 10; });
    blocks.forEach(function(b, i){
      if(heights[i] > limit){ var z = (limit - 4) / heights[i]; b.style.zoom = z; heights[i] = heights[i] * z; }   // very rare: one block taller than a page
    });
    var pages = paginate(heights, blocks.map(function(b){ return b.getAttribute('data-keep') === '1'; }), limit);
    var wm = d.getElementById('tpl-wm').textContent.replace(/<\\\//g, '</'), foot = d.getElementById('tpl-ftr').textContent.replace(/<\\\//g, '</');
    pages.forEach(function(idxs, pi){
      var pg = d.createElement('div');
      pg.className = 'page';
      pg.innerHTML = wm + '<div class="phdr"><span>Pawniac &middot; ' + esc(title) + '</span><span>Page ' + (pi + 1) + ' of ' + pages.length + '</span></div><div class="pbody"></div>' + foot;
      var body = pg.querySelector('.pbody');
      idxs.forEach(function(i){ body.appendChild(blocks[i]); });
      pagesEl.appendChild(pg);
    });
    src.parentNode.removeChild(src);
    return pages.length;
  }

  function makePdf(btn){
    var H = window.__anHook, A = H && H.data();
    if(!H){ alert('The PDF report needs "patch 2" (analyze-patch-2.html). Apply it to your index.html first.'); return; }
    if(!A){ alert('Run an analysis first.'); return; }
    var label = btn.textContent;
    btn.disabled = true; btn.textContent = 'Preparing PDF...';
    setTimeout(function(){
      var fr = null, oldTitle = document.title;
      function cleanup(){
        document.title = oldTitle;
        if(fr && fr.parentNode) fr.parentNode.removeChild(fr);
        fr = null;
      }
      try{
        var white = A.hdr.White || 'White', black = A.hdr.Black || 'Black';
        var title = white + ' vs ' + black;
        var fileTitle = 'Pawniac analysis - ' + title;
        var blocks = buildBlocks(H, A, reportCards(H));
        fr = document.createElement('iframe');
        fr.setAttribute('aria-hidden', 'true');
        fr.style.cssText = 'position:fixed;left:-10000px;top:0;width:794px;height:1123px;border:0;';
        document.body.appendChild(fr);
        var d = fr.contentDocument;
        d.open(); d.write(docHtml(blocks, fileTitle, white, black)); d.close();
        layoutPages(d, title);
        document.title = fileTitle;
        var w = fr.contentWindow;
        w.addEventListener('afterprint', cleanup);
        setTimeout(function(){ if(fr) cleanup(); }, 10 * 60 * 1000);
        setTimeout(function(){ try{ w.focus(); w.print(); }catch(e){ console.error(e); alert("Couldn't open the print window."); cleanup(); } }, 250);
      }catch(e){
        console.error('pdf failed', e);
        alert("Couldn't build the PDF: " + (e && e.message ? e.message : e));
        cleanup();
      }finally{
        btn.disabled = false; btn.textContent = label;
      }
    }, 30);
  }

